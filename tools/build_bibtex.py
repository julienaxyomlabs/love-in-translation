#!/usr/bin/env python3
"""Build evidence/references.bib from the DOIs cited in the paper (DOI content negotiation).

Citation keys are normalised to ``<firstauthor><year><firstword>``. Needs network access.

Usage: python3 tools/build_bibtex.py --out evidence/references.bib
"""

from __future__ import annotations

import argparse
import re
import sys
import time
import unicodedata
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path
from typing import Dict, List, Optional

ROOT = Path(__file__).resolve().parents[1]
DOI_RE = re.compile(r"10\.\d{4,9}/[^\s\"'`<>]+")
USER_AGENT = "love-in-translation-bibtex/0.1"
SKIP_WORDS = {"a", "an", "the", "on", "of", "in", "and", "to", "for", "is", "are", "what", "why", "how", "when", "does"}


def clean(doi: str) -> str:
    doi = doi.rstrip(".,;:*_")
    for opening, closing in (("(", ")"), ("[", "]")):
        while doi.endswith(closing) and doi.count(opening) < doi.count(closing):
            doi = doi[:-1].rstrip(".,;:*_")
    return doi


def ascii_slug(text: str) -> str:
    norm = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]", "", norm.lower())


def fetch_bibtex(doi: str) -> Optional[str]:
    url = "https://doi.org/" + urllib.parse.quote(doi, safe="/")
    request = urllib.request.Request(url, headers={"Accept": "application/x-bibtex; charset=utf-8", "User-Agent": USER_AGENT})
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            text = response.read().decode("utf-8", "replace").strip()
            return text if text.startswith("@") else None
    except (urllib.error.URLError, TimeoutError, ValueError):
        return None


def field(entry: str, name: str) -> str:
    match = re.search(name + r"\s*=\s*[{\"](.+?)[}\"]\s*[,}]", entry, re.S | re.I)
    return match.group(1) if match else ""


def make_key(entry: str, used: Dict[str, int]) -> str:
    authors = field(entry, "author")
    first = authors.split(" and ")[0] if authors else "anon"
    family = first.split(",")[0] if "," in first else first.split()[-1] if first.split() else "anon"
    year = field(entry, "year") or "nd"
    title_words = [w for w in re.findall(r"[A-Za-z]+", field(entry, "title")) if w.lower() not in SKIP_WORDS]
    base = ascii_slug(family) + year + (ascii_slug(title_words[0]) if title_words else "")
    used[base] = used.get(base, 0) + 1
    return base if used[base] == 1 else f"{base}{chr(ord('a') + used[base] - 1)}"


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--out", default="evidence/references.bib")
    parser.add_argument("--delay", type=float, default=0.2)
    args = parser.parse_args(argv)

    dois: List[str] = []
    for path in sorted((ROOT / "paper").glob("*.md")):
        for match in DOI_RE.findall(path.read_text(encoding="utf-8")):
            doi = clean(match)
            if doi not in dois:
                dois.append(doi)

    used: Dict[str, int] = {}
    entries, missing = [], []
    for doi in sorted(dois, key=str.lower):
        raw = fetch_bibtex(doi)
        time.sleep(args.delay)
        if raw is None:
            missing.append(doi)
            continue
        key = make_key(raw, used)
        entries.append((key, re.sub(r"^@(\w+)\{[^,]*,", lambda m: "@" + m.group(1).lower() + "{" + key + ",", raw, count=1)))

    header = [
        "% references.bib: generated by tools/build_bibtex.py from the DOIs cited in paper/",
        f"% {len(entries)} entries via DOI content negotiation; {len(missing)} DOI(s) returned no BibTeX",
    ] + [f"% no BibTeX available: {d}" for d in missing]
    body = "\n\n".join(text for _, text in sorted(entries))
    out = ROOT / args.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(header) + "\n\n" + body + "\n", encoding="utf-8")
    print(f"wrote {len(entries)} entries to {args.out}; {len(missing)} without BibTeX")
    return 0


if __name__ == "__main__":
    sys.exit(main())
